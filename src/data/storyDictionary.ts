export function lookupStoryWord(rawWord: string): DictionaryEntry | null {
  const clean = rawWord.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!clean) return null;

  if (STORY_DICTIONARY[clean]) {
    return STORY_DICTIONARY[clean];
  }

  // Basic stem checks
  if (clean.endsWith('ing') && STORY_DICTIONARY[clean.slice(0, -3)]) {
    return STORY_DICTIONARY[clean.slice(0, -3)];
  }
  if (clean.endsWith('ed') && STORY_DICTIONARY[clean.slice(0, -2)]) {
    return STORY_DICTIONARY[clean.slice(0, -2)];
  }
  if (clean.endsWith('ed') && STORY_DICTIONARY[clean.slice(0, -1)]) {
    return STORY_DICTIONARY[clean.slice(0, -1)];
  }
  if (clean.endsWith('s') && STORY_DICTIONARY[clean.slice(0, -1)]) {
    return STORY_DICTIONARY[clean.slice(0, -1)];
  }
  if (clean.endsWith('es') && STORY_DICTIONARY[clean.slice(0, -2)]) {
    return STORY_DICTIONARY[clean.slice(0, -2)];
  }

  return null;
}
